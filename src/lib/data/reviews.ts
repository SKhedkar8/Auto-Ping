// In-memory / dynamic store for newly submitted reviews
let customReviews: ServiceReview[] = [];

export function getCenterReviews(centerId?: string): ServiceReview[] {
  const all = [...customReviews, ...SEED_REVIEWS];
  if (!centerId) return all;
  return all.filter((r) => r.centerId === centerId);
}

export function getAllReviews(): ServiceReview[] {
  return [...customReviews, ...SEED_REVIEWS];
}

export function addServiceReview(review: Omit<ServiceReview, 'id' | 'date' | 'helpfulCount' | 'verifiedBooking'>): ServiceReview {
  const newReview: ServiceReview = {
    ...review,
    id: `rev-custom-${Date.now()}-${Math.random().toString(36).substr(2, 5)}`,
    date: 'Just now',
    verifiedBooking: true,
    helpfulCount: 1,
  };
  customReviews = [newReview, ...customReviews];
  return newReview;
}
